"""
Generates src/app/features/community/components/world-land.ts: the land of the events map as one SVG path on a
1° grid (equirectangular, 78°N to 58°S, Antarctica left out). Each row of land cells is merged into
runs, so the path stays small; the UI fills it with a pixel pattern.

The land mask comes from the global-land-mask package (MIT, Todd Karin), see ATTRIBUTION.md.
WIDTH, HEIGHT and LAT_TOP must match the WORLD_* constants in src/app/features/community/community.model.ts.

    pip install "global-land-mask==1.0.0" "numpy>=1.26"
    python3 apps/web/scripts/world-map.py
"""
from pathlib import Path

import numpy as np
from global_land_mask import globe

LAT_TOP, LAT_BOTTOM = 78, -58
WIDTH, HEIGHT = 360, LAT_TOP - LAT_BOTTOM

parts = []
for row in range(HEIGHT):
    lat = LAT_TOP - row - 0.5
    land = globe.is_land(np.full(WIDTH, lat), np.arange(-180, 180) + 0.5).astype(int)
    edges = np.diff(np.concatenate([[0], land, [0]]))
    for start, end in zip(np.where(edges == 1)[0], np.where(edges == -1)[0]):
        parts.append(f"M{start} {row}h{end - start}v1h-{end - start}z")

out = Path(__file__).resolve().parents[1] / "src/app/features/community/components/world-land.ts"
out.write_text(
    "// Generated by apps/web/scripts/world-map.py: do not edit.\n"
    "// Grid: 1 unit = 1°, x = longitude + 180, y = 78 - latitude (WORLD_* constants in data/api.ts).\n"
    "/** Land cells, merged into one run per row stretch. */\n"
    f"export const WORLD_LAND = '{''.join(parts)}';\n"
)
print(out, len(parts), "runs")
