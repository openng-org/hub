import compatibility from '../data/compatibility.json' with { type: 'json' };

/**
 * Official Angular version compatibility matrix for Node.js, TypeScript, and RxJS.
 * Older Angular versions (≤8) also include Angular CLI compatibility.
 *
 * @see https://angular.dev/reference/versions
 */
export interface AngularVersionCompatibility {
  /** Angular version range (e.g. "22.0.x", "21.0.x || 21.1.x || 21.2.x") */
  angular: string;
  /** Node.js semver range */
  node: string;
  /** TypeScript semver range */
  typescript: string;
  /** RxJS semver range */
  rxjs: string;
  /** Angular CLI version range (only for Angular ≤8) */
  angularCli?: string;
}

/**
 * Angular version compatibility entries, newest first (data/compatibility.json, generated by
 * `pnpm data:sync versions` from https://angular.dev/reference/versions).
 */
export const angularVersionCompatibility: AngularVersionCompatibility[] = compatibility;
